import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import { mkdtempSync, mkdirSync, realpathSync, readFileSync, rmSync, writeFileSync, existsSync, readdirSync, statSync } from "node:fs";
import { createServer, type ServerResponse } from "node:http";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { createInterface } from "node:readline";
import { test } from "node:test";
import { SessionManager } from "@earendil-works/pi-coding-agent";
import { ProjectStore } from "../src/core/store.ts";
import { TeamController } from "../src/core/controller.ts";
import { ensureView } from "../src/core/navigation.ts";
import type { ExtensionContext } from "@earendil-works/pi-coding-agent";

const delay = (ms: number) => new Promise(resolve => setTimeout(resolve, ms));
async function until(fn: () => boolean, message: string) { for (let i = 0; i < 300; i++) { if (fn()) return; await delay(50); } throw Error(`Timed out: ${message}`); }
test("real Pi RPC replacement preserves a genuinely pending local worker", { timeout: 60000 }, async t => {
  const temp = realpathSync(mkdtempSync(join(tmpdir(), "codexteams-rpc-"))), root = join(temp, "project"), agent = join(temp, "agent"), sessions = join(temp, "sessions");
  mkdirSync(root); mkdirSync(agent); mkdirSync(sessions);
  let response: ServerResponse | undefined, requests = 0;
  const server = createServer(async (_req, res) => { requests++; response = res; for await (const _chunk of _req) {} });
  await new Promise<void>(r => server.listen(0, "127.0.0.1", r));
  const address = server.address(); assert.ok(address && typeof address === "object");
  writeFileSync(join(agent, "models.json"), JSON.stringify({ providers: { openai: { baseUrl: `http://127.0.0.1:${address.port}/v1`, api: "openai-completions", apiKey: "local-fixture-only", models: [{ id: "gpt-6.1-sol", name: "fixture", reasoning: true, input: ["text"], contextWindow: 32000, maxTokens: 2048, cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0 } }] } } }));
  const store = ProjectStore.open(root), team = new TeamController(store, { runner: async () => { throw Error("unexpected"); }, validateProfile: async () => {} });
  team.add("developer", "pending fixture");
  const parent = SessionManager.create(root, sessions);
  parent.appendMessage({ role: "user", content: [{ type: "text", text: "Local RPC replacement checkpoint" }], timestamp: Date.now() });
  const parentFile = parent.getSessionFile()!;
  const view = ensureView(store, { cwd: root, sessionManager: parent } as unknown as ExtensionContext, "task", "task-1");
  await team.shutdown();
  const env: NodeJS.ProcessEnv = { PI_CODING_AGENT_DIR: agent };
  for (const key of ["PATH", "HOME", "TMPDIR", "LANG", "LC_ALL"]) if (process.env[key] !== undefined) env[key] = process.env[key];
  const child = spawn(resolve("node_modules/.bin/pi"), ["--mode", "rpc", "--approve", "--offline", "--no-extensions", "-e", resolve("src/index.ts"), "--session", parentFile], { cwd: root, env, stdio: ["pipe", "pipe", "pipe"] });
  const records: any[] = []; let stderr = ""; child.stderr.setEncoding("utf8"); child.stderr.on("data", chunk => { stderr += chunk; });
  createInterface({ input: child.stdout }).on("line", line => { try { records.push(JSON.parse(line)); } catch { records.push({ invalid: line }); } });
  t.after(async () => { response?.destroy(); child.stdin.end(); if (child.exitCode === null && child.signalCode === null) { child.kill("SIGTERM"); await Promise.race([new Promise(r => child.once("close", r)), delay(3000)]); } await new Promise<void>(r => server.close(() => r())); rmSync(temp, { recursive: true, force: true }); });
  async function command(id: string, type: string, fields = {}) {
    child.stdin.write(JSON.stringify({ id, type, ...fields }) + "\n");
    await until(() => records.some(r => r.type === "response" && r.id === id) || child.exitCode !== null, `response ${id}: ${stderr}`);
    const result = records.find(r => r.type === "response" && r.id === id);
    assert.ok(result, `missing response ${id}: ${stderr}`); assert.equal(result.success, true, JSON.stringify(result)); return result.data;
  }
  await command("run", "prompt", { message: "/teams run task-1" });
  await until(() => requests === 1 && Boolean(response), `worker request; stderr=${stderr}`);
  const stateFile = join(root, ".codexteams", "state.json"), lock = join(root, ".codexteams", "lock.json");
  const state = () => JSON.parse(readFileSync(stateFile, "utf8"));
  const before = state().tasks[0].attempts[0]; assert.ok(before.workerPid); assert.ok(existsSync(lock));
  const otherRoot = join(temp, "other"); mkdirSync(otherRoot);
  const other = SessionManager.create(otherRoot, sessions);
  other.appendMessage({ role: "user", content: [{ type: "text", text: "Connected second project checkpoint" }], timestamp: Date.now() });
  const otherFile = other.getSessionFile()!;
  assert.equal((await command("worker-to-other", "switch_session", { sessionPath: otherFile })).cancelled, false);
  await command("other-add", "prompt", { message: "/teams add developer connected second team" });
  const otherLock = join(otherRoot, ".codexteams", "lock.json"); assert.ok(existsSync(otherLock));
  assert.equal(state().tasks[0].status, "running"); assert.equal(state().tasks[0].attempts[0].workerPid, before.workerPid);
  assert.equal((await command("worker-back", "switch_session", { sessionPath: parentFile })).cancelled, false);
  assert.equal((await command("new", "new_session")).cancelled, false);
  assert.equal((await command("switch", "switch_session", { sessionPath: parentFile })).cancelled, false);
  const messages = (await command("fork-list", "get_fork_messages")).messages;
  assert.ok(messages.length); assert.equal((await command("fork", "fork", { entryId: messages[0].entryId })).cancelled, false);
  const current = state().tasks[0].attempts[0]; assert.equal(current.id, before.id); assert.equal(current.sessionId, before.sessionId); assert.equal(current.workerPid, before.workerPid); assert.ok(existsSync(lock)); assert.equal(requests, 1);
  const workerDir = join(root, ".codexteams", "sessions");
  const workerName = readdirSync(workerDir).find(name => name.endsWith(`_${before.sessionId}.jsonl`)); assert.ok(workerName);
  const workerFile = join(workerDir, workerName), original = readFileSync(workerFile), originalStat = statSync(workerFile);
  assert.equal((await command("reject-original", "switch_session", { sessionPath: workerFile })).cancelled, true);
  assert.deepEqual(readFileSync(workerFile), original); assert.equal(statSync(workerFile).mtimeMs, originalStat.mtimeMs);
  assert.equal((await command("view", "switch_session", { sessionPath: view.file })).cancelled, false);
  await command("readonly-prompt", "prompt", { message: "This prompt must not cause inference" });
  await command("readonly-mutation", "prompt", { message: "/teams add developer forbidden" });
  const blockedBash = await command("readonly-bash", "bash", { command: "touch forbidden-file" });
  assert.equal(blockedBash.exitCode, 1); assert.equal(existsSync(join(root, "forbidden-file")), false);
  assert.equal(state().tasks.length, 1); assert.equal(requests, 1);
  assert.equal((await command("clone-view", "clone")).cancelled, false);
  await command("cloned-prompt", "prompt", { message: "Cloned view must remain readonly" });
  await command("cloned-mutation", "prompt", { message: "/teams add developer forbidden clone" });
  const clonedBash = await command("cloned-bash", "bash", { command: "touch forbidden-clone" });
  assert.equal(clonedBash.exitCode, 1); assert.equal(existsSync(join(root, "forbidden-clone")), false);
  const cloneForkMessages = (await command("clone-fork-list", "get_fork_messages")).messages;
  assert.ok(cloneForkMessages.length);
  assert.equal((await command("clone-fork", "fork", { entryId: cloneForkMessages[0].entryId })).cancelled, false);
  await command("forked-prompt", "prompt", { message: "Forked view remains readonly" });
  const forkedBash = await command("forked-bash", "bash", { command: "touch forbidden-fork" });
  assert.equal(forkedBash.exitCode, 1); assert.equal(existsSync(join(root, "forbidden-fork")), false);
  assert.equal(state().tasks.length, 1); assert.equal(requests, 1);
  await command("home", "prompt", { message: "/teams home" });
  assert.deepEqual(readFileSync(workerFile), original); assert.equal(statSync(workerFile).ino, originalStat.ino); assert.equal(statSync(workerFile).mtimeMs, originalStat.mtimeMs);
  assert.equal(state().tasks[0].status, "running"); assert.equal(state().tasks[0].attempts[0].workerPid, before.workerPid);
  response!.writeHead(200, { "Content-Type": "text/event-stream" });
  response!.end(`data: ${JSON.stringify({ id: "fixture", object: "chat.completion.chunk", created: 1, model: "gpt-6.1-sol", choices: [{ index: 0, delta: { role: "assistant", content: "fixture completed" }, finish_reason: "stop" }], usage: { prompt_tokens: 1, completion_tokens: 1, total_tokens: 2 } })}\n\ndata: [DONE]\n\n`);
  response = undefined;
  await until(() => state().tasks[0].status === "needs_review", `worker completion; stderr=${stderr}`);
  assert.equal(state().tasks[0].attempts[0].id, before.id); assert.equal(requests, 1);
  await command("check", "prompt", { message: "/teams check task-1 while [ ! -f check-release ]; do sleep 0.05; done; printf verified" });
  await until(() => state().tasks[0].checks[0]?.workerPid > 0, "pending check");
  const check = state().tasks[0].checks[0];
  assert.equal((await command("new-check", "new_session")).cancelled, false);
  assert.equal((await command("return-check", "switch_session", { sessionPath: parentFile })).cancelled, false);
  const checkForkMessages = (await command("check-fork-list", "get_fork_messages")).messages;
  assert.ok(checkForkMessages.length);
  assert.equal((await command("check-fork", "fork", { entryId: checkForkMessages[0].entryId })).cancelled, false);
  assert.equal(state().tasks[0].checks[0].id, check.id); assert.equal(state().tasks[0].checks[0].workerPid, check.workerPid);
  writeFileSync(join(root, "check-release"), "release");
  await until(() => state().tasks[0].checks[0].status === "passed", `check completion; stderr=${stderr}`);
  assert.equal(requests, 1);
  await command("check-quit", "prompt", { message: "/teams check task-1 while [ ! -f never-release ]; do sleep 0.05; done" });
  await until(() => state().tasks[0].checks[1]?.workerPid > 0, "pending final check");
  assert.equal((await command("quit-other", "switch_session", { sessionPath: otherFile })).cancelled, false);
  assert.equal(state().tasks[0].checks[1].status, "running"); assert.ok(existsSync(lock));
  child.stdin.end(); await until(() => child.exitCode !== null, "Pi exit");
  assert.equal(child.exitCode, 0, stderr); assert.equal(existsSync(lock), false); assert.equal(existsSync(otherLock), false);
  assert.equal(state().tasks[0].checks[1].status, "interrupted");
});
