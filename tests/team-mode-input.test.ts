import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, rmSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import extension from "../src/index.ts";
import { TeamModeSupervisor } from "../src/core/team-mode.ts";
import { processRegistry } from "../src/core/process-registry.ts";
import { realpathSync } from "node:fs";
import type { ExtensionAPI, ExtensionCommandContext, ExtensionContext } from "@earendil-works/pi-coding-agent";

test("mode input is handled, rejects images, and OFF leaves normal input alone", async t => {
  const root = mkdtempSync(join(tmpdir(), "codexteams-mode-input-")); const handlers = new Map<string, Function>(); const messages: string[] = [];
  let command!: (args: string, ctx: ExtensionCommandContext) => Promise<void>;
  const ctx = { cwd: root, mode: "rpc", hasUI: false, isProjectTrusted: () => true, isIdle: () => true, modelRegistry: {}, sessionManager: { getSessionId: () => "session-1", getSessionFile: () => undefined, getBranch: () => [] } } as unknown as ExtensionCommandContext;
  const pi = { registerCommand: (_: string, d: { handler: typeof command }) => { command = d.handler; }, registerTool: () => {}, on: (name: string, fn: Function) => { handlers.set(name, fn); return () => {}; }, sendMessage: (message: { content: string }) => messages.push(message.content) } as unknown as ExtensionAPI;
  extension(pi); t.after(async () => { await handlers.get("session_shutdown")!({ reason: "quit" }, ctx); rmSync(root, { recursive: true, force: true }); });
  const input = (event: object) => handlers.get("input")!(event, ctx as ExtensionContext);
  assert.deepEqual(await input({ source: "rpc", text: "hello" }), { action: "continue" });
  await command("mode on", ctx);
  const tool = handlers.get("tool_call")!;
  assert.equal((await tool({ toolName: "write", parentToolCallId: "outer" }, ctx)).block, true);
  assert.equal(await tool({ toolName: "read" }, ctx), undefined);
  assert.equal((await handlers.get("user_bash")!({ command: "touch file" }, ctx)).result.exitCode, 1);
  let captures = 0, failIntake = false; t.mock.method(TeamModeSupervisor.prototype, "ingest", () => { if (failIntake) throw new Error("disk failure"); captures++; return "request-1"; });
  assert.deepEqual(await input({ source: "rpc", text: "hello" }), { action: "handled" });
  assert.equal(captures, 1);
  assert.deepEqual(await input({ source: "rpc", text: "image", images: [{ type: "image" }] }), { action: "handled" });
  assert.equal(captures, 1);
  assert.deepEqual(await input({ source: "extension", text: "internal" }), { action: "continue" });
  failIntake = true;
  assert.deepEqual(await input({ source: "rpc", text: "failure" }), { action: "handled" });
  assert.match(messages.join("\n"), /이미지|첨부/); assert.match(messages.join("\n"), /disk failure/);
  await command("mode off", ctx);
  assert.equal(await tool({ toolName: "write" }, ctx), undefined);
  const owner = processRegistry().owners.get(realpathSync(root))!;
  t.mock.getter(owner.controller, "busy", () => true);
  assert.equal((await tool({ toolName: "write" }, ctx)).block, true);
  assert.equal((await handlers.get("user_bash")!({ command: "touch file" }, ctx)).result.exitCode, 1);
  assert.deepEqual(await input({ source: "rpc", text: "normal" }), { action: "continue" });
});
